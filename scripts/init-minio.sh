#!/usr/bin/env bash
# Creates the bucket, applies the hard quota and creates the MCP users (idempotent).
# Usage: ./scripts/init-minio.sh   (BUCKET=lake QUOTA=5GiB by default)
#   mcp-access-0.env  read-only user, committed with a default password
#   mcp-access-1.env  read/write user, git-ignored; generated here with a random password if missing
set -euo pipefail
cd "$(dirname "$0")/.."
set -a; . ./minio.env; set +a
BUCKET="${BUCKET:-lake}"; QUOTA="${QUOTA:-5GiB}"
POLICIES="$(mktemp -d)"; trap 'rm -rf "$POLICIES"' EXIT; chmod a+rx "$POLICIES"
mc() { docker run --rm --network spark_spark -v "${POLICIES}:/policies:ro" -e "MC_HOST_local=http://${MINIO_ROOT_USER}:${MINIO_ROOT_PASSWORD}@minio:9000" cgr.dev/chainguard/minio-client:latest "$@"; }
mc mb --ignore-existing "local/${BUCKET}"
mc quota set "local/${BUCKET}" --size "${QUOTA}"
mc quota info "local/${BUCKET}"

# policies scoped to the one bucket (not the built-in readonly/readwrite, which cover every bucket)
policy() {  # name, actions
  printf '{"Version":"2012-10-17","Statement":[{"Effect":"Allow","Action":[%s],"Resource":["arn:aws:s3:::%s","arn:aws:s3:::%s/*"]}]}\n' "$2" "$BUCKET" "$BUCKET" > "${POLICIES}/$1.json"
  chmod a+r "${POLICIES}/$1.json"
  mc admin policy create local "$1" "/policies/$1.json"
}
mcp_user() {  # env file, policy
  local user pass
  user="$(sed -n 's/^MCP_S3_USER=//p' "$1")"; pass="$(sed -n 's/^MCP_S3_PASSWORD=//p' "$1")"
  mc admin user add local "$user" "$pass"
  mc admin policy attach local "$2" --user "$user" 2>&1 | grep -v "already" || true
  echo "MCP user ${user}: policy ${2}"
}
policy "${BUCKET}-ro" '"s3:GetObject","s3:ListBucket","s3:GetBucketLocation"'
policy "${BUCKET}-rw" '"s3:GetObject","s3:ListBucket","s3:GetBucketLocation","s3:PutObject","s3:DeleteObject","s3:AbortMultipartUpload","s3:ListMultipartUploadParts","s3:ListBucketMultipartUploads"'
mcp_user mcp-access-0.env "${BUCKET}-ro"
if [ ! -f mcp-access-1.env ]; then
  printf '# MinIO credentials of the MCP server with MCP_EDIT_ACCESS=1 (read/write on the bucket). Generated by scripts/init-minio.sh; git-ignored.\nMCP_S3_USER=mcp-editor\nMCP_S3_PASSWORD=%s\n' "$(openssl rand -hex 16)" > mcp-access-1.env
  chmod 600 mcp-access-1.env
fi
mcp_user mcp-access-1.env "${BUCKET}-rw"
